#!/usr/bin/env python3
"""Legacy helper to build a flattened, variant-aware memory-crash dataset.

The public benchmark task list is keyed by base task stem, but the updated data
tree contains multiple memory-crash variants for a few base tasks. This script
keeps every instance by using the instance directory name as the task stem.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path


def _base_stem(instance_name: str) -> str:
    marker = "__memory_crash__"
    if marker not in instance_name:
        raise ValueError(f"not a memory-crash instance name: {instance_name}")
    return instance_name.split(marker, 1)[0]


def _copytree(src: Path, dst: Path) -> None:
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst, symlinks=True)


def _write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def build_dataset(repo_root: Path, output_dir: Path) -> list[str]:
    data_dir = repo_root / "data"
    ref_dir = data_dir / "evaluation" / "references"
    cache_dir = data_dir / "evaluation" / "references_cache"

    instances = sorted(data_dir.glob("*__memory_crash__*"))
    if not instances:
        raise RuntimeError(f"no memory-crash instances found under {data_dir}")

    if output_dir.exists():
        shutil.rmtree(output_dir)
    for subdir in ("input", "prompts", "testbench", "evaluation/references"):
        (output_dir / subdir).mkdir(parents=True, exist_ok=True)
    if (data_dir / "references").exists():
        _copytree(data_dir / "references", output_dir / "references")

    task_list = {
        "_doc": "Flattened memory-crash variants generated by scripts/make_memory_crash_variant_dataset.py",
        "schema_version": 1,
        "n_total": len(instances),
        "entries": [],
    }
    aliases: list[str] = []
    missing_caches: list[str] = []

    for instance in instances:
        alias = instance.name
        base = _base_stem(alias)
        aliases.append(alias)

        input_meta = json.loads((instance / "input.json").read_text(encoding="utf-8"))
        input_meta["task_id"] = alias
        input_meta["original_task_id"] = input_meta.get("original_task_id", base)
        input_meta["memory_crash_instance"] = alias
        _write_json(output_dir / "input" / f"{alias}.json", input_meta)

        shutil.copy2(instance / "prompt.txt", output_dir / "prompts" / f"{alias}.txt")
        _copytree(instance / "testbench", output_dir / "testbench" / alias)

        ref_path = ref_dir / f"{base}.json"
        if not ref_path.exists():
            raise FileNotFoundError(f"missing reference for {alias}: {ref_path}")
        ref = json.loads(ref_path.read_text(encoding="utf-8"))
        ref["task_id"] = alias
        ref.setdefault("source_task_id", base)
        _write_json(output_dir / "evaluation" / "references" / f"{alias}.json", ref)

        copied_cache = False
        if cache_dir.exists():
            for src_cache in cache_dir.glob(f"*/{base}.json"):
                sig = src_cache.parent.name
                cache = json.loads(src_cache.read_text(encoding="utf-8"))
                cache["task_id"] = alias
                _write_json(
                    output_dir / "evaluation" / "references_cache" / sig / f"{alias}.json",
                    cache,
                )
                copied_cache = True
        if not copied_cache:
            missing_caches.append(alias)

        broken_start = instance / "broken_start.cu"
        if not broken_start.exists():
            raise FileNotFoundError(f"missing broken_start for {alias}: {broken_start}")
        task_list["entries"].append({
            "stem": alias,
            "task_id": alias,
            "base_stem": base,
            "error_category": "memory_crash",
            "broken_start": {
                "code_path": str(broken_start.relative_to(repo_root)),
                "error_category": "memory_crash",
                "log_excerpt": "",
            },
        })

    _write_json(output_dir / "task_list.json", task_list)
    (output_dir / "tasks.txt").write_text("\n".join(aliases) + "\n", encoding="utf-8")
    if missing_caches:
        (output_dir / "missing_reference_cache.txt").write_text(
            "\n".join(missing_caches) + "\n", encoding="utf-8"
        )
    return aliases


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("benchmark/generated/memcrash32_variant_dataset"),
    )
    args = parser.parse_args()

    aliases = build_dataset(args.repo_root.resolve(), args.output_dir.resolve())
    print(f"wrote {len(aliases)} memory-crash variants to {args.output_dir.resolve()}")
    print(f"task_list: {args.output_dir.resolve() / 'task_list.json'}")


if __name__ == "__main__":
    main()
